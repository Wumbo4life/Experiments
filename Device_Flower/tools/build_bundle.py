#!/usr/bin/env python3
"""Pack ./assets into plain <script> files under ./js/bundle.

Everything is embedded as base64 so the game also runs when index.html is
opened straight from disk (file://), where fetch() and @font-face are blocked.

    python3 tools/build_bundle.py
"""
import base64
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ASSETS = os.path.join(ROOT, "assets")
OUT = os.path.join(ROOT, "js", "bundle")

HEADER = "/* Generated by tools/build_bundle.py - do not edit by hand. */\n" \
         "window.DF_DATA = window.DF_DATA || {};\n"


def b64(path):
    with open(path, "rb") as fh:
        return base64.b64encode(fh.read()).decode("ascii")


def write(name, body):
    path = os.path.join(OUT, name)
    with open(path, "w") as fh:
        fh.write(HEADER + body)
    print("%-12s %7.1f KB" % (name, os.path.getsize(path) / 1024))


def main():
    os.makedirs(OUT, exist_ok=True)

    with open(os.path.join(ASSETS, "atlas.json")) as fh:
        atlas = json.load(fh)
    atlas["image"] = "data:image/png;base64," + b64(os.path.join(ASSETS, "atlas.png"))
    write("atlas.js", "DF_DATA.atlas = %s;\n" % json.dumps(atlas, separators=(",", ":")))

    fonts = {
        "main": b64(os.path.join(ASSETS, "fonts", "main.ttf")),
        "mono": b64(os.path.join(ASSETS, "fonts", "main_mono.ttf")),
    }
    write("fonts.js", "DF_DATA.ttf = %s;\n" % json.dumps(fonts))

    sounds = {}
    for name in sorted(os.listdir(os.path.join(ASSETS, "sounds"))):
        if name.endswith(".mp3"):
            sounds[name[:-4]] = b64(os.path.join(ASSETS, "sounds", name))
    lines = ["DF_DATA.sounds = {"]
    for key, data in sounds.items():
        lines.append('"%s":"%s",' % (key, data))
    lines.append("};\n")
    write("sounds.js", "\n".join(lines))


if __name__ == "__main__":
    main()
